// Bundles the worker into one file the Supabase Edge Runtime (Deno) can run.
// pg and zod are loaded through Deno's npm: specifier instead of being inlined.
import { readFileSync } from "node:fs";
import { build } from "esbuild";

const version = (name) => JSON.parse(readFileSync(`node_modules/${name}/package.json`, "utf8")).version;
const pgVersion = version("pg");
const zodVersion = version("zod");

await build({
  entryPoints: ["supabase/functions/worker/entry.ts"],
  outfile: "supabase/functions/worker/index.ts",
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  tsconfig: "tsconfig.json",
  external: ["npm:*", "node:*"],
  alias: { pg: `npm:pg@${pgVersion}`, zod: `npm:zod@${zodVersion}` },
  banner: { js: '// @ts-nocheck\n// Generated by scripts/build-edge-worker.mjs. Do not edit.\nimport process from "node:process";' },
  legalComments: "none",
  minify: true,
  logLevel: "info",
});
