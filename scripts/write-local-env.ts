/**
 * Writes .env.local for LOCAL development from `supabase status`. The values
 * are the well-known local-stack defaults, not production secrets. Refuses to
 * overwrite an existing .env.local unless --force is passed.
 */
import { execSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";
import { randomBytes } from "node:crypto";

const force = process.argv.includes("--force");
if (existsSync(".env.local") && !force) {
  console.error(".env.local already exists; pass --force to overwrite");
  process.exit(1);
}

// A fixed command line through the shell: on Windows `npx` is npx.cmd, which
// cannot be spawned directly.
const raw = execSync("npx supabase status -o json", { encoding: "utf8" });
const s = JSON.parse(raw.slice(raw.indexOf("{")));
const lines = [
  "# Generated by scripts/write-local-env.ts for the LOCAL Supabase stack only.",
  `NEXT_PUBLIC_SUPABASE_URL=${s.API_URL}`,
  `NEXT_PUBLIC_SUPABASE_ANON_KEY=${s.ANON_KEY}`,
  `SUPABASE_SERVICE_ROLE_KEY=${s.SERVICE_ROLE_KEY}`,
  `DATABASE_URL=${s.DB_URL}`,
  "APP_URL=http://localhost:3000",
  `ENCRYPTION_KEY=${randomBytes(32).toString("base64")}`,
  `WORKFLOW_SECRET=${randomBytes(24).toString("base64url")}`,
  "WORKER_CONCURRENCY=2",
  "SIMULATION_STEP_MS=4000",
  "LOG_LEVEL=info",
  "",
];
writeFileSync(".env.local", lines.join("\n"), { mode: 0o600 });
console.log("Wrote .env.local for the local Supabase stack");
